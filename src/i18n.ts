const MONTH_FULL_MR = ['जानेवारी', 'फेब्रुवारी', 'मार्च', 'एप्रिल', 'मे', 'जून', 'जुलै', 'ऑगस्ट', 'सप्टेंबर', 'ऑक्टोबर', 'नोव्हेंबर', 'डिसेंबर'];
const DOW_EN = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
const DOW_MR = ['रवि', 'सोम', 'मंगळ', 'बुध', 'गुरू', 'शुक्र', 'शनि'];

const mr = () => cur === 'mr';
/** Localized names. */
export const nm = {
  tithi: (n: number) => (mr() ? tithiNameMr(n) : tithiName(n)),
  paksha: (n: number) => (mr() ? pakshaMr(n) : paksha(n)),
  /** "Shukla Pratipada" / "शुद्ध प्रतिपदा" */
  pakshaTithi: (n: number) => `${nm.paksha(n)} ${nm.tithi(n)}`,
  nakshatra: (i: number) => (mr() ? NAKSHATRAS_MR[i] : NAKSHATRAS[i]),
  rashi: (i: number) => (mr() ? RASHIS_MR[i] : RASHIS[i]),
  /** presiding deity of a nakshatra */
  devata: (i: number) => NAKSHATRA_DEVATA[i][mr() ? 1 : 0],
  /** aradhya vriksha (worship tree) of a nakshatra */
  vriksha: (i: number) => NAKSHATRA_VRIKSHA[i][mr() ? 1 : 0],
  vrikshaBotanical: (i: number) => NAKSHATRA_VRIKSHA[i][2],
  yoga: (i: number) => (mr() ? YOGAS_MR[i] : YOGAS[i]),
  karana: (k: number) => (mr() ? karanaNameMr(k) : karanaName(k)),
  isVishti: (k: number) => karanaName(k) === 'Vishti',
  vara: (wd: number) => (mr() ? VARAS_MR[wd] : `${VARAS[wd]} · ${VARAS_EN[wd]}`),
  graha: (g: string) => (mr() ? GRAHA_MR[g] : GRAHA_NAMES[g]),
  earth: () => t('scene.earth'),
  monthShort: (m: number) => (mr() ? MONTH_SHORT_MR[m] : MONTH_SHORT_EN[m]),
  dow: (d: number) => (mr() ? DOW_MR[d] : DOW_EN[d]),
  weekday: (d: number) => (mr() ? VARAS_MR[d] : VARAS_EN[d]),
  monthFull: (m: number) => (mr() ? MONTH_FULL_MR[m] : MONTH_FULL_EN[m]),
  kaal: (k: Kaal) => KAAL[k][mr() ? 1 : 0],
  catChip: (c: Category) => CAT[c][mr() ? 1 : 0],
  catKicker: (c: Category) => (mr() ? CAT_MR_KICKER[c] : `${CAT[c][2]} · ${CAT_MR_KICKER[c]}`),
};
